// 100 2000 42 10000000000 1.5 3.14 A true
class Main {
    public static void main(String[] args) {
        byte b = 100;
        short s = 2000;
        int x = 42;
        long n = 10_000_000_000L;
        float f = 1.5f;
        double d = 3.14;
        char c = 'A';
        boolean ok = true;
        System.out.println(b + " " + s + " " + x + " " + n + " " + f + " " + d + " " + c + " " + ok);
    }
}
